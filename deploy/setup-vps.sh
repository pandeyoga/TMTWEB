#!/usr/bin/env bash
# Sets up (or repairs) the Triyasa website on a VPS that may already host other projects. Safe to re-run.
#   cd /opt/triyasa-web && ADMIN_PASSWORD='...' bash deploy/setup-vps.sh
# It never touches ports 80/443 or other containers: the site runs on its own port (8080 or the next free one).
set -euo pipefail
cd "$(dirname "$0")/.."
source deploy/config.sh

if [ "$(id -u)" -ne 0 ]; then echo "Jalankan sebagai root (sudo -i)."; exit 1; fi
say() { printf '\n\033[1;34m== %s\033[0m\n' "$*"; }
on_error() {
  echo
  echo "✗ Setup berhenti karena error (baris $1). Ringkasan untuk diagnosa:"
  docker compose ps -a 2>/dev/null || true
  docker compose logs --no-color --tail=60 app 2>/dev/null || true
  echo "Jalankan ulang setelah diperbaiki: cd $(pwd) && ADMIN_PASSWORD='...' bash deploy/setup-vps.sh"
}
trap 'on_error $LINENO' ERR
env_get() { grep -E "^$1=" .env 2>/dev/null | tail -1 | cut -d= -f2-; }
port_used() {
  if command -v ss >/dev/null 2>&1; then ss -ltnH "( sport = :$1 )" | grep -q . && return 0; fi
  (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null && return 0
  docker ps --format '{{.Ports}}' 2>/dev/null | grep -qE "[:.]$1->" && return 0
  return 1
}

say "0. Kondisi server"
. /etc/os-release 2>/dev/null && echo "OS      : ${PRETTY_NAME:-?}"
echo "RAM     : $(awk '/MemTotal/ {printf "%.1f GB", $2/1048576}' /proc/meminfo)   Swap: $(awk '/SwapTotal/ {printf "%.1f GB", $2/1048576}' /proc/meminfo)"
echo "Disk /  : $(df -h / | awk 'NR==2 {print $4 " kosong dari " $2}')"
echo "Port 80 : $(port_used 80 && echo dipakai || echo kosong)   Port 443: $(port_used 443 && echo dipakai || echo kosong)"
command -v docker >/dev/null 2>&1 && echo "Docker  : $(docker --version)  · container berjalan: $(docker ps -q | wc -l)" || echo "Docker  : belum terpasang"

say "1. Paket dasar & Docker"
apt-get update -y >/dev/null
apt-get install -y ca-certificates curl git openssl iproute2 >/dev/null
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
fi
if ! docker compose version >/dev/null 2>&1; then
  apt-get install -y docker-compose-plugin || { echo "✗ Plugin 'docker compose' tidak tersedia. Pasang Docker Compose v2 lalu ulangi."; exit 1; }
fi
docker compose version

say "2. Memori untuk build"
MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
FREE_GB=$(df -BG / | awk 'NR==2 {gsub("G","",$4); print $4}')
if [ "$MEM_MB" -lt 6000 ] && ! swapon --show | grep -q . ; then
  if [ "$FREE_GB" -gt 12 ]; then
    fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
    grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
    echo "✓ Swap 4 GB ditambahkan"
  else
    echo "! RAM < 6 GB tanpa swap dan disk sempit; build bisa gagal karena memori."
  fi
else
  echo "✓ Memori cukup"
fi

say "3. File .env"
if [ ! -f .env ]; then
  PORT="$APP_PORT_DEFAULT"
  while port_used "$PORT"; do PORT=$((PORT + 1)); done
  cat > .env <<ENV
# Generated by deploy/setup-vps.sh — keep a private copy of this file.
APP_PORT=${PORT}
APP_BIND=0.0.0.0
SITE_URL=http://${VPS_IP}:${PORT}
SITE_ADDRESS=:80
POSTGRES_PASSWORD=$(openssl rand -hex 24)
PAYLOAD_SECRET=$(openssl rand -hex 32)
PREVIEW_SECRET=$(openssl rand -hex 16)
ENV
  chmod 600 .env
  echo "✓ .env dibuat · website memakai port ${PORT}"
else
  echo "- .env sudah ada, tidak diubah (port $(env_get APP_PORT))"
fi
PORT="$(env_get APP_PORT)"
URL="$(env_get SITE_URL)"

say "4. Firewall"
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then
  ufw allow "${PORT}/tcp" >/dev/null && echo "✓ ufw: port ${PORT} dibuka"
else
  echo "- ufw tidak aktif, dilewati"
fi
echo "  Jika VPS memakai firewall dari panel penyedia (mis. Hostinger hPanel), buka juga port TCP ${PORT} di sana."

say "5. Build & jalankan (beberapa menit pada build pertama)"
docker compose up -d --build

say "6. Menunggu aplikasi & migrasi database"
for i in $(seq 1 100); do
  if curl -fs -o /dev/null "http://127.0.0.1:${PORT}/api/users/me" 2>/dev/null; then echo "✓ Aplikasi aktif"; break; fi
  [ "$i" -eq 100 ] && { echo "✗ Aplikasi tidak merespons. Lihat: docker compose logs --tail=100 app"; exit 1; }
  sleep 3
done

say "7. Konten awal (dilewati jika sudah ada)"
docker compose --profile tools run --rm -T seed

say "8. Akun super admin"
if [ -n "${ADMIN_PASSWORD:-}" ]; then
  docker compose --profile tools run --rm -T \
    -e ADMIN_EMAIL="${ADMIN_EMAIL}" -e ADMIN_PASSWORD="${ADMIN_PASSWORD}" \
    seed sh -c 'corepack enable pnpm && pnpm create-admin'
else
  echo "- ADMIN_PASSWORD tidak diberikan; buat akun admin pertama lewat ${URL}/admin"
fi

chmod +x deploy/*.sh
say "Selesai"
echo "  Website : ${URL}"
echo "  CMS     : ${URL}/admin   (login: ${ADMIN_EMAIL})"
echo "  Ganti password admin setelah login pertama."
echo "  Update  : cd ${APP_DIR} && bash deploy/update.sh"
